-- Jalankan SQL ini di Supabase Dashboard -> SQL Editor -> New Query

create table if not exists public.sentiment_predictions (
  id bigint generated by default as identity primary key,
  review_text text not null,
  sentiment text not null,
  confidence double precision default 0,
  prob_positif double precision default 0,
  prob_netral double precision default 0,
  prob_negatif double precision default 0,
  product_name text,
  category text,
  created_at timestamptz default now()
);

create table if not exists public.online_learning_logs (
  id bigint generated by default as identity primary key,
  review_text text not null,
  target_label text not null,
  category text default 'Real-Time Input',
  created_at timestamptz default now()
);

-- Aktifkan RLS & izinkan akses API backend
alter table public.sentiment_predictions enable row level security;
alter table public.online_learning_logs enable row level security;

create policy "Allow insert predictions" on public.sentiment_predictions
  for insert with check (true);

create policy "Allow select predictions" on public.sentiment_predictions
  for select using (true);

create policy "Allow insert online learning" on public.online_learning_logs
  for insert with check (true);

create policy "Allow select online learning" on public.online_learning_logs
  for select using (true);
